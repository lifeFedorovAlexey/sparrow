function parserSource() {
  return `import * as cheerio from "cheerio";
import { config } from "./config.js";

function readField($, item, field, baseUrl) {
  const element = $(item).find(field.selector).first();
  if (field.attribute === "text") return element.text().trim();
  const value = String(element.attr(field.attribute) ?? "");
  return ["href", "src"].includes(field.attribute) && value ? new URL(value, baseUrl).toString() : value;
}

export async function scrape({ url = config.url, fetchImpl = fetch } = {}) {
  const response = await fetchImpl(url, { headers: { "user-agent": config.userAgent } });
  if (!response.ok) throw new Error(\`HTTP \${response.status} while loading \${url}\`);
  const $ = cheerio.load(await response.text());
  return $(config.containerSelector).map((_, item) => Object.fromEntries(
    config.fields.map((field) => [field.name, readField($, item, field, url)]),
  )).get();
}
`;
}

function cliSource() {
  return `import { writeFile } from "node:fs/promises";
import { scrape } from "./parser.js";

try {
  const records = await scrape();
  const output = JSON.stringify(records, null, 2);
  await writeFile("output.json", output + "\\n", "utf8");
  console.log(output);
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
`;
}

export function renderProjectFiles({ projectId, task, containerSelector, mappings }) {
  const config = {
    url: task.url,
    containerSelector,
    fields: mappings.map(({ field, selector, attribute }) => ({ name: field, selector, attribute })),
    userAgent: "HermesGeneratedParser/0.1",
  };
  return new Map([
    ["package.json", `${JSON.stringify({ name: projectId, version: "0.1.0", private: true, type: "module", scripts: { start: "node src/cli.js" }, dependencies: { cheerio: "^1.1.2" } }, null, 2)}\n`],
    ["src/config.js", `export const config = ${JSON.stringify(config, null, 2)};\n`],
    ["src/parser.js", parserSource()],
    ["src/cli.js", cliSource()],
    ["README.md", `# ${projectId}\n\nGenerated by Hermes Parser AI.\n\n\`\`\`bash\nnpm install\nnpm start\n\`\`\`\n`],
    ["Dockerfile", "FROM node:22-alpine\nWORKDIR /app\nCOPY package*.json ./\nRUN npm install --omit=dev\nCOPY src ./src\nCMD [\"npm\", \"start\"]\n"],
  ]);
}
